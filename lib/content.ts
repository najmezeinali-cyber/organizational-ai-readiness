const domainPrefixes: Record<Domain, string> = { engineering: 'E', procurement: 'P', project: 'M' };

function exampleFor(example: string, domain: Domain): string {
  // Split only explicitly labelled examples; unlabelled shared advice keeps its source meaning.
  const labels = { engineering: 'مهندسی', procurement: 'تدارکات', project: 'پروژه' };
  const match = example.match(new RegExp(`${labels[domain]}: ([^؛]+)`));
  return match ? match[1].trim() : example;
}

export function questionsFor(domain: Domain): Question[] {
  if (!Object.hasOwn(domainPrefixes, domain)) throw new Error('حوزه نامعتبر است.');
  return axes.flatMap(axis => questionBank
    .filter(q => q.axis === axis.id && (!/^[EPM]/.test(q.id) || q.id.startsWith(domainPrefixes[domain])))
    .map(q => ({ ...q, options: [...q.options], example: exampleFor(q.example, domain) })));
}
